

CREATE TABLE IF NOT EXISTS risk_settings(
  user_id INT PRIMARY KEY, cfg TEXT NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE) ENGINE=InnoDB;
 
CREATE TABLE IF NOT EXISTS risk_positions(
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, side ENUM('BUY','SELL') NOT NULL,
  lots DECIMAL(10,3) NOT NULL, entry DECIMAL(12,3) NOT NULL, sl DECIMAL(12,3) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX(user_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE) ENGINE=InnoDB;