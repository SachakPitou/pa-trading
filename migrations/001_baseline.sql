-- Baseline schema (safe on an existing database: every statement is IF NOT EXISTS).
CREATE TABLE IF NOT EXISTS users(
  id INT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(190) UNIQUE NOT NULL,
  pass_hash VARCHAR(255) NOT NULL, telegram_chat_id VARCHAR(40) NULL,
  alert_telegram TINYINT(1) DEFAULT 0, alert_email TINYINT(1) DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS signals(
  id INT AUTO_INCREMENT PRIMARY KEY, symbol VARCHAR(20),
  tier VARCHAR(10) NOT NULL DEFAULT 'confirmed',
  side ENUM('BUY','SELL'),
  entry DECIMAL(12,3), sl DECIMAL(12,3), tp1 DECIMAL(12,3), tp2 DECIMAL(12,3),
  conf TINYINT, status ENUM('OPEN','TP1','SL','EXP') DEFAULT 'OPEN', r DECIMAL(5,2) NULL,
  reasons VARCHAR(255) NULL,
  candle_time VARCHAR(25), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  closed_at TIMESTAMP NULL, UNIQUE KEY u(symbol,candle_time)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS journal(
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, side ENUM('BUY','SELL'),
  lots DECIMAL(8,2), entry DECIMAL(12,3), exit_price DECIMAL(12,3), pnl DECIMAL(12,2),
  note VARCHAR(255) NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX(user_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS cache(ckey VARCHAR(100) PRIMARY KEY, cval MEDIUMTEXT, updated INT) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS login_attempts(ip VARCHAR(45), at INT, INDEX(ip)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS api_usage(day DATE PRIMARY KEY, n INT NOT NULL DEFAULT 0) ENGINE=InnoDB;
